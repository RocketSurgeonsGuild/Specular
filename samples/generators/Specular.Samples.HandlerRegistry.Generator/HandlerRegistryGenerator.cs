using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Specular.Scanning;

namespace Specular.Samples.HandlerRegistry.Generator;

/// <summary>
///     Writes a <c>HandlerTypes</c> class listing every concrete <c>IHandler</c> the project can see: its own and those of the assemblies
///     it references. A small third-party generator built on Specular.Scanning.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class HandlerRegistryGenerator : IIncrementalGenerator
{
    // Names this generator's cache file, obj/<tfm>/ctp/Specular.Samples.HandlerRegistry.ctpjson. It has to be unique among the
    // generators a project uses, so it carries the generator's own name rather than something generic like "Handlers".
    private const string ConsumerId = "Specular.Samples.HandlerRegistry";

    // Looked up by name: the generator never references the handlers library, it only knows the contract.
    private const string HandlerInterfaceName = "Specular.Samples.HandlerRegistry.IHandler";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // A ScanRequest is a value (it records names, not symbols), so although this runs on every compilation, an unchanged request
        // compares equal and nothing downstream reruns.
        var requests = context.CompilationProvider.SelectMany(static (compilation, _) => CreateRequests(compilation));

        // Scan reuses each referenced assembly's matches while that assembly is unchanged: in memory between runs in the IDE, and across
        // command-line builds through the cache file, which the build hands back as an additional file. Only the project's own source is
        // rescanned on every run.
        var results = context.Scan(ConsumerId, requests);

        // The result is equatable too, so the source below is regenerated only when the set of handlers actually changes.
        context.RegisterSourceOutput(results, static (output, result) => output.AddSource("HandlerTypes.g.cs", Render(result)));
    }

    private static ImmutableArray<ScanRequest> CreateRequests(Compilation compilation)
    {
        // A project that cannot see IHandler has no handlers: no request, so no scan and no output.
        if (compilation.GetTypeByMetadataName(HandlerInterfaceName) is not { } handler)
        {
            return [];
        }

        // The same selector shape as Specular's runtime scanning, over symbols. Only the assembly declaring IHandler and those that
        // reference it can hold handlers, so the rest of the references (the framework, every package) are never walked.
        var request = ScanRequest.Build(
            compilation,
            s => s
                .FromAssemblyOf(handler)
                .DependenciesFromAssemblyOf(handler)
                .GetTypes(f => f.AssignableTo(handler).KindOf(TypeKind.Class).NotInfoOf(TypeInfoFilter.Abstract))
        );
        return [request];
    }

    private static string Render(ScanResult result)
    {
        var source = new StringBuilder();
        _ = source
           .AppendLine("// <auto-generated/>")
           .AppendLine("#nullable enable")
           .AppendLine()
           .AppendLine("namespace Specular.Samples.HandlerRegistry")
           .AppendLine("{")
           .AppendLine("/// <summary>Every concrete IHandler this project can reference, found at compile time.</summary>")
           .AppendLine("internal static class HandlerTypes")
           .AppendLine("{")
           // Plain C# that every language version the consuming project might use understands.
           .AppendLine("    public static global::System.Collections.Generic.IReadOnlyList<global::System.Type> All { get; } = new global::System.Type[]")
           .AppendLine("    {");

        foreach (var type in result.Types)
        {
            // A scan sees every type, including another assembly's internal ones; typeof() on those would not compile here. The result
            // says which ones this compilation may reference (InternalsVisibleTo included), so no symbols are needed to decide.
            if (!type.IsAccessible)
            {
                continue;
            }

            // A generic type, or one nested in a generic type (its metadata name carries the arity, as in Outer`1+Inner), has no single
            // closed Type to list.
            if (type.MetadataName.IndexOf('`') >= 0)
            {
                continue;
            }

            // Metadata names separate nested types with '+'; C# uses '.'.
            _ = source.Append("        typeof(global::").Append(type.MetadataName.Replace('+', '.')).AppendLine("),");
        }

        _ = source.AppendLine("    };");

        // Left as comments so the generated file shows what the scan found but could not use.
        foreach (var type in result.Types)
        {
            if (!type.IsAccessible)
            {
                _ = source
                   .Append("    // Not accessible from this project: ")
                   .Append(type.MetadataName)
                   .Append(" (")
                   .Append(type.AssemblyName)
                   .AppendLine(")");
            }
        }

        return source.AppendLine("}").AppendLine("}").ToString();
    }
}
